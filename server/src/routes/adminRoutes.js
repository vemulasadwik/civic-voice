const router = require("express").Router();
const authenticate = require("../middleware/authMiddleware");
const authorizeRoles = require("../middleware/roleMiddleware");
const controller = require("../controllers/adminController");
const { listComments, addComment } = require("../controllers/commentController");
router.use(authenticate, authorizeRoles("admin"));
router.get("/dashboard", controller.dashboard);
router.get("/reports.csv", controller.csvReport);
router.get("/complaints", controller.listAllComplaints);
router.get("/complaints/:id", controller.getAdminComplaint);
router.patch("/complaints/:id/assign", controller.assignComplaint);
router.patch("/complaints/:id/priority", controller.setPriority);
router.patch("/complaints/:id/status", controller.adminChangeStatus);
router.get("/users", controller.listUsers);
router.post("/officers", controller.createOfficer);
router.patch("/users/:id", controller.updateUser);
router.get("/complaints/:id/comments", listComments);
router.post("/complaints/:id/comments", addComment);
module.exports = router;
